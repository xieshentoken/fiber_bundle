def router() -> APIRouter:
    routes = APIRouter()

    @routes.get("/")
    def index() -> Response:
        return Response((WEB_ROOT / "index.html").read_bytes(), media_type="text/html")

    @routes.get("/static/{filename:path}")
    def static(filename: str) -> Response:
        if filename not in STATIC_ASSETS:
            raise Denied(404)
        return Response((WEB_ROOT / filename).read_bytes(), media_type=STATIC_ASSETS[filename])

    return routes
